-- Portal bookings on days the sheet did not deduct must not add heads on top of this ledger.
insert into public.agent_allotment_daily (day, agent_slug, agent_name, total_deduct, note)
select b.date::date, 'booking-window', 'Booking Window', 0,
       'BW ledger: no head use on the deposit sheet'
from public.bookings b
where b.agent_slug = 'booking-window'
  and b.status <> 'Cancelled'
  and b.date >= '2026-05-09'
  and b.date <= '2026-10-03'
  and not exists (
    select 1 from public.agent_allotment_daily d
    where d.agent_slug = 'booking-window' and d.day = b.date::date
  )
group by b.date::date;
